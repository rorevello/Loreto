#!/usr/bin/env python3
"""LaTeX for the paper's Figure 1: the example in Turtle and in Loreto, every token coloured.

    python experiments/figures/figure1_tokens.py

The Turtle text is playground/examples/paper-figure.ttl and the Loreto text is loreto.serialize of it with
the default options, so they are exactly what the Playground shows for that example. Each token of
o200k_base gets a box in one of the Playground's five token colours, in turn (the colours of
playground/app/static/style.css, made opaque over white).

Writes tokens_turtle.tex and tokens_loreto.tex next to this script. Each file is
self-contained: \\input it inside a minipage.
"""
from __future__ import annotations

import sys
from pathlib import Path

import rdflib
import tiktoken

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO))
import loreto  # noqa: E402

OUT = HERE

# --tok-0 … --tok-4 of style.css (light theme): rgb and alpha.
TOKEN_COLOURS = [((59, 130, 246), 0.17), ((16, 185, 129), 0.19), ((245, 158, 11), 0.22),
                 ((236, 72, 153), 0.16), ((139, 92, 246), 0.17)]
SPECIAL = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "#": r"\#", "%": r"\%", "&": r"\&",
           "_": r"\_", "^": r"\^{}", "~": r"\textasciitilde{}", "$": r"\$", " ": r"\ "}


def opaque(rgb, alpha) -> str:
    return "".join(f"{round(255 - alpha * (255 - c)):02X}" for c in rgb)


def escape(text: str) -> str:
    return "".join(SPECIAL.get(ch, ch) for ch in text)


def token_lines(text: str, encoding) -> list:
    """The text as lines, each a list of (colour index, piece); a token that spans a newline is
    split, and both parts keep its colour."""
    lines, current = [], []
    for i, tok in enumerate(encoding.encode(text, disallowed_special=())):
        parts = encoding.decode([tok]).split("\n")
        for k, part in enumerate(parts):
            if k > 0:
                lines.append(current)
                current = []
            if part:
                current.append((i % len(TOKEN_COLOURS), part))
    if current:
        lines.append(current)
    return lines


def latex(text: str, encoding) -> str:
    head = [f"% Generated by experiments/figures/figure1_tokens.py: one box per o200k_base token."]
    head += [f"\\definecolor{{loretotok{k}}}{{HTML}}{{{opaque(*c)}}}" for k, c in enumerate(TOKEN_COLOURS)]
    head += [r"\providecommand{\loretotk}[2]{\colorbox{loretotok#1}{\rule[-1.8pt]{0pt}{7.2pt}#2}}",
             r"\par\begingroup\ttfamily\scriptsize\setlength{\fboxsep}{0pt}\setlength{\parindent}{0pt}"]
    body = []
    for line in token_lines(text, encoding):
        boxes = "".join(f"\\loretotk{{{c}}}{{{escape(piece)}}}" for c, piece in line)
        body.append(f"\\mbox{{{boxes}}}\\par")
    return "\n".join(head + body + [r"\endgroup", ""])


def main() -> None:
    encoding = tiktoken.get_encoding("o200k_base")
    turtle = (REPO / "playground" / "examples" / "paper-figure.ttl").read_text(encoding="utf-8")
    text = loreto.serialize(rdflib.Graph().parse(data=turtle, format="turtle"))
    OUT.mkdir(parents=True, exist_ok=True)
    for name, t in (("tokens_turtle.tex", turtle), ("tokens_loreto.tex", text)):
        (OUT / name).write_text(latex(t, encoding), encoding="utf-8")
        print(f"{name}: {len(encoding.encode(t, disallowed_special=()))} tokens")


if __name__ == "__main__":
    main()
